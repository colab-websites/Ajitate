from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import json
OUT=Path(__file__).parent
with sync_playwright() as p:
 browser=p.chromium.launch()
 page=browser.new_page(viewport={'width':1440,'height':1000}, reduced_motion='reduce')
 errors=[]
 page.on('pageerror', lambda e: errors.append(str(e)))
 page.goto('http://127.0.0.1:5173/Ajitate/',wait_until='domcontentloaded')
 expect(page.locator('#menu h2')).to_be_visible()
 page.evaluate('document.fonts.ready')
 # Load below-fold images for full-page review; this changes test DOM only.
 page.evaluate("document.querySelectorAll('img').forEach(i=>i.loading='eager')")
 page.wait_for_function("Array.from(document.images).every(i=>i.complete)",timeout=60000)
 broken=page.evaluate("Array.from(document.images).filter(i=>!i.naturalWidth).map(i=>i.src)")
 assert not broken, broken
 results=[]
 for width,height in [(360,800),(390,844),(768,1024),(1024,768),(1440,1000)]:
  page.set_viewport_size({'width':width,'height':height})
  page.evaluate('window.scrollTo(0,0)')
  expect(page.locator('.floating-header')).not_to_have_class(__import__('re').compile('is-scrolled'))
  page.wait_for_function('document.documentElement.scrollWidth <= innerWidth')
  assert page.locator('video').evaluate('(v)=>v.paused'), 'Reduced motion video is playing'
  page.screenshot(path=str(OUT/f'after-{width}-hero.png'))
  page.locator('#menu').evaluate('(el)=>window.scrollTo(0,el.offsetTop-120)')
  expect(page.locator('.floating-header')).to_have_class(__import__('re').compile('is-scrolled'))
  page.screenshot(path=str(OUT/f'after-{width}-menu.png'))
  results.append({'viewport':f'{width}x{height}','overflow':False,'reduced_motion_video_paused':True})
 page.set_viewport_size({'width':390,'height':844})
 page.get_by_role('button',name='Abrir menú',exact=True).click()
 expect(page.locator('#mobile-nav')).to_be_visible()
 page.keyboard.press('Escape')
 expect(page.locator('#mobile-nav')).to_have_count(0)
 expect(page.get_by_role('button',name='Abrir menú',exact=True)).to_be_focused()
 search=page.get_by_role('searchbox',name='Buscar en el menú',exact=True)
 search.fill('pina')
 expect(page.locator('#menu-products .food-card')).to_have_count(1)
 expect(page.locator('#menu-products')).to_contain_text('Piña')
 search.fill('xyz-unavailable')
 expect(page.locator('.menu-empty')).to_be_visible()
 page.locator('.menu-empty button').click()
 expect(search).to_have_value('')
 page.get_by_role('button',name='Agregar Solo Queso?',exact=True).click()
 expect(page.locator('.cart-floating')).to_contain_text('$3,50')
 expect(page.locator('.order-toast')).to_contain_text('agregado')
 page.locator('.cart-floating').click()
 expect(page.get_by_role('dialog')).to_be_visible()
 expect(page.locator('.cart-total')).to_contain_text('$3,50')
 page.get_by_role('button',name='Aumentar Solo Queso?',exact=True).click()
 expect(page.locator('.cart-total')).to_contain_text('$7,00')
 page.get_by_role('button',name='Eliminar Solo Queso?',exact=True).click()
 expect(page.locator('.empty-cart')).to_contain_text('Tu próximo antojo')
 page.get_by_role('button',name='Cerrar pedido').click()
 page.get_by_role('button',name='Ver Solo Queso?',exact=True).click()
 page.get_by_role('radio',name='Combo con papas',exact=True).check()
 page.get_by_role('button',name='Aumentar cantidad',exact=True).click()
 page.get_by_role('button',name='Agregar al pedido').click()
 expect(page.locator('.cart-total')).to_contain_text('$10,98')
 page.get_by_role('button',name='Continuar').click()
 page.get_by_label('Tu nombre',exact=True).fill('Prueba local')
 page.get_by_label('Teléfono',exact=True).fill('0991234567')
 page.get_by_role('radio',name='Retiro en el local').check()
 page.get_by_role('button',name='Revisar pedido').click()
 expect(page.locator('.order-summary')).to_contain_text('2 × Solo Queso? · Combo: Papas + bebida: $10,98')
 page.screenshot(path=str(OUT/'after-mobile-order.png'))
 page.keyboard.press('Escape')
 expect(page.get_by_role('dialog')).not_to_be_visible()
 page.set_viewport_size({'width':1440,'height':1000})
 page.evaluate('window.scrollTo(0,0)')
 page.screenshot(path=str(OUT/'after-desktop-full.png'),full_page=True)
 for section in ['especiales','nosotros','momentos','resenas','ubicacion']:
  page.locator('#'+section).evaluate('(el)=>window.scrollTo(0,el.getBoundingClientRect().top+scrollY-120)')
  page.screenshot(path=str(OUT/f'after-desktop-{section}.png'))
 assert not errors,errors
 (OUT/'results.json').write_text(json.dumps({'viewports':results,'broken_images':broken,'page_errors':errors,'checks':['mobile nav Escape and focus return','accent-insensitive search','empty search recovery','quick-add toast','cart increment and removal','combo subtotal $10.98','pickup inquiry summary','dialog Escape'],'real_orders_sent':False},indent=2))
 print('PASS: 5 viewports, images, navigation, search, cart and local inquiry summary')
 browser.close()
